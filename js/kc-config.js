/**
 * KC — маленький рантайм-хелпер поверх конфига.
 * Нормализует хэндлы соцсетей в полные URL и даёт доступ к текущему языку,
 * чтобы остальной код не гадал, что именно вписали в настройки.
 */
window.KC = (function (cfg) {
  function toUrl(value, base) {
    var v = String(value || "").trim();
    if (!v) return "";
    if (/^https?:\/\//i.test(v)) return v;
    return base + v.replace(/^@/, "");
  }

  // Язык хранит js/lang-switcher.js в localStorage под ключом "kc-lang".
  function lang() {
    try {
      return localStorage.getItem("kc-lang") === "uz" ? "uz" : "ru";
    } catch (e) {
      return "ru"; // приватный режим / отключённое хранилище
    }
  }

  // Кнопки языка обрабатывает lang-switcher, отдельного события он не шлёт —
  // поэтому подписываемся на те же клики, чтобы перерисовать свои блоки.
  function onLangChange(callback) {
    document.addEventListener("click", function (e) {
      var btn = e.target.closest ? e.target.closest(".kc-lang-btn") : null;
      if (btn) setTimeout(callback, 0);
    });
  }

  return {
    cfg: cfg,
    telegramUrl: toUrl(cfg.telegram, "https://t.me/"),
    instagramUrl: toUrl(cfg.instagram, "https://instagram.com/"),
    lang: lang,
    onLangChange: onLangChange,
  };
})(window.KC_CONFIG);
